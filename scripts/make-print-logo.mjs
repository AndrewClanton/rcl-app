// Turns the Royale wordmark into a 1-bit raster the receipt printer can
// print at the top of movie tickets, and writes it to
// src/lib/print/logo-raster.ts. Run again if the logo changes.
//
// Usage: node scripts/make-print-logo.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const WIDTH = 448; // of the TM-m30's 576-dot line; a multiple of 8
const { data, info } = await sharp("src/app/admin/schedule-graphic/assets/logo.png").resize({ width: WIDTH }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });

// The wordmark is light letters on transparent: any solid pixel prints black.
const bytesPerRow = info.width / 8;
const out = new Uint8Array(bytesPerRow * info.height);
for (let y = 0; y < info.height; y++)
  for (let x = 0; x < info.width; x++)
    if (data[(y * info.width + x) * 4 + 3] > 110) out[y * bytesPerRow + (x >> 3)] |= 0x80 >> (x & 7);

writeFileSync(
  "src/lib/print/logo-raster.ts",
  `// Generated by scripts/make-print-logo.mjs from the Royale wordmark. Do not edit.
import type { Raster } from "./raster";

export const LOGO_RASTER: Raster = { width: ${info.width}, height: ${info.height}, data: "${Buffer.from(out).toString("base64")}" };
`,
);
console.log(`logo raster ${info.width}x${info.height}, ${out.length} bytes`);
